// Builds supabase/migrations/<timestamp>_places_data.sql from the GeoNames
// cities1000 export (towns with 1,000+ people), shipped in the
// `cities-with-1000` npm package. GeoNames data is CC BY 4.0: credit
// "GeoNames" wherever places are shown.
//
// Usage: node scripts/build-places-migration.mjs 20261031010000

import fs from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const stamp = process.argv[2];
if (!/^\d{14}$/.test(stamp ?? "")) {
  console.error("Pass a migration timestamp, e.g. 20261031010000");
  process.exit(1);
}

const { file } = require("cities-with-1000");
const countries = new Intl.DisplayNames(["en"], { type: "region" });

// Short regions for the US and Canada, where "Portland, OR" is how people
// write it. GeoNames uses postal codes for US states, numbers for provinces.
const US_STATES = {
  AL: "Alabama",
  AK: "Alaska",
  AZ: "Arizona",
  AR: "Arkansas",
  CA: "California",
  CO: "Colorado",
  CT: "Connecticut",
  DE: "Delaware",
  DC: "District of Columbia",
  FL: "Florida",
  GA: "Georgia",
  HI: "Hawaii",
  ID: "Idaho",
  IL: "Illinois",
  IN: "Indiana",
  IA: "Iowa",
  KS: "Kansas",
  KY: "Kentucky",
  LA: "Louisiana",
  ME: "Maine",
  MD: "Maryland",
  MA: "Massachusetts",
  MI: "Michigan",
  MN: "Minnesota",
  MS: "Mississippi",
  MO: "Missouri",
  MT: "Montana",
  NE: "Nebraska",
  NV: "Nevada",
  NH: "New Hampshire",
  NJ: "New Jersey",
  NM: "New Mexico",
  NY: "New York",
  NC: "North Carolina",
  ND: "North Dakota",
  OH: "Ohio",
  OK: "Oklahoma",
  OR: "Oregon",
  PA: "Pennsylvania",
  RI: "Rhode Island",
  SC: "South Carolina",
  SD: "South Dakota",
  TN: "Tennessee",
  TX: "Texas",
  UT: "Utah",
  VT: "Vermont",
  VA: "Virginia",
  WA: "Washington",
  WV: "West Virginia",
  WI: "Wisconsin",
  WY: "Wyoming",
};
const CA_PROVINCES = {
  "01": ["AB", "Alberta"],
  "02": ["BC", "British Columbia"],
  "03": ["MB", "Manitoba"],
  "04": ["NB", "New Brunswick"],
  "05": ["NL", "Newfoundland and Labrador"],
  "07": ["NS", "Nova Scotia"],
  "08": ["ON", "Ontario"],
  "09": ["PE", "Prince Edward Island"],
  10: ["QC", "Quebec"],
  11: ["SK", "Saskatchewan"],
  12: ["YT", "Yukon"],
  13: ["NT", "Northwest Territories"],
  14: ["NU", "Nunavut"],
};

const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const rows = [];
for (const line of fs.readFileSync(file, "utf8").split("\n")) {
  if (!line.trim()) continue;
  const f = line.split("\t");
  const [id, name, ascii, , lat, lng] = f;
  const country = f[8];
  const admin1 = f[10];
  const population = Number(f[14]) || 0;

  let regionCode = null;
  let regionName = null;
  if (country === "US" && US_STATES[admin1]) [regionCode, regionName] = [admin1, US_STATES[admin1]];
  if (country === "CA" && CA_PROVINCES[admin1]) [regionCode, regionName] = CA_PROVINCES[admin1];

  let countryName = country;
  try {
    countryName = countries.of(country) ?? country;
  } catch {}

  rows.push(
    `(${Number(id)},${q(name)},${q(ascii || name)},${q(regionCode)},${q(regionName)},${q(country)},${q(countryName)},${Number(lat)},${Number(lng)},${population})`,
  );
}

const out = [
  "-- GeoNames cities1000 (towns with 1,000+ people), CC BY 4.0, via the",
  "-- cities-with-1000 npm package (GeoNames export of March 2020).",
  "-- Generated by scripts/build-places-migration.mjs. Do not edit by hand.",
  "",
];
for (let i = 0; i < rows.length; i += 1000) {
  out.push(
    "insert into public.places (id, name, ascii_name, region_code, region_name, country_code, country_name, latitude, longitude, population) values",
    rows.slice(i, i + 1000).join(",\n") + ";",
    "",
  );
}

const path = `supabase/migrations/${stamp}_places_data.sql`;
fs.writeFileSync(path, out.join("\n"));
console.log(`Wrote ${rows.length} places to ${path}`);
